CREATE DATABASE HOTEL;

USE HOTEL;
GO


CREATE TABLE Huespedes (
    ID_CLIENTE INT PRIMARY KEY IDENTITY(1,1),
    NOMBRE_DEL_CLIENTE VARCHAR(50) NOT NULL,
    TIPO_DE_DOCUMENTO VARCHAR(25) NOT NULL,
    NO_DE_DOCUMENTO VARCHAR(25) NOT NULL UNIQUE,
    TELEFONO VARCHAR(20),
    CORREO VARCHAR(50)
);


CREATE TABLE Tipo_Habitaciones (
    ID_TIPO INT PRIMARY KEY IDENTITY(1,1),
    TIPO VARCHAR(30) NOT NULL,
    PRECIO DECIMAL(10,2) NOT NULL,
    DESCRIPCION VARCHAR(MAX)
);


CREATE TABLE Habitaciones (
    ID_HABITACION INT PRIMARY KEY IDENTITY(1,1),
    NUMERO_HABITACION VARCHAR(10) NOT NULL UNIQUE,
    ID_TIPO INT NOT NULL,
    ESTADO VARCHAR(20) DEFAULT 'Disponible',
    ESTADO_LIMPIEZA VARCHAR(20) DEFAULT 'Limpia',
    FOREIGN KEY (ID_TIPO) REFERENCES Tipo_Habitaciones(ID_TIPO)
);


CREATE TABLE Empleados (
    ID_EMPLEADO INT PRIMARY KEY IDENTITY(1,1),
    NOMBRE VARCHAR(50) NOT NULL,
    IDENTIFICACION VARCHAR(25) NOT NULL UNIQUE,
    TELEFONO VARCHAR(15),
    CARGO VARCHAR(50),
    SALARIO DECIMAL(10,2)
);


CREATE TABLE Reservaciones (
    ID_RESERVACION INT PRIMARY KEY IDENTITY(1,1),
    ID_CLIENTE INT NOT NULL,
    ID_HABITACION INT NOT NULL,
    ID_EMPLEADO INT,
    FECHA_RESERVA DATETIME DEFAULT GETDATE(),
    FECHA_ENTRADA DATE NOT NULL,
    FECHA_SALIDA DATE NOT NULL,
    ESTADO VARCHAR(20) DEFAULT 'Confirmada',
    FOREIGN KEY (ID_CLIENTE) REFERENCES Huespedes(ID_CLIENTE),
    FOREIGN KEY (ID_HABITACION) REFERENCES Habitaciones(ID_HABITACION),
    FOREIGN KEY (ID_EMPLEADO) REFERENCES Empleados(ID_EMPLEADO)
);


CREATE TABLE Servicios (
    ID_SERVICIO INT PRIMARY KEY IDENTITY(1,1),
    NOMBRE_SERVICIO VARCHAR(50) NOT NULL,
    PRECIO DECIMAL(10,2) NOT NULL
);


CREATE TABLE Detalle_Servicios (
    ID_DETALLE INT PRIMARY KEY IDENTITY(1,1),
    ID_RESERVACION INT NOT NULL,
    ID_SERVICIO INT NOT NULL,
    CANTIDAD INT DEFAULT 1,
    FECHA_CONSUMO DATETIME DEFAULT GETDATE(),
    FOREIGN KEY (ID_RESERVACION) REFERENCES Reservaciones(ID_RESERVACION),
    FOREIGN KEY (ID_SERVICIO) REFERENCES Servicios(ID_SERVICIO)
);


CREATE TABLE Pagos (
    ID_PAGO INT PRIMARY KEY IDENTITY(1,1),
    ID_RESERVACION INT NOT NULL,
    FECHA_PAGO DATETIME DEFAULT GETDATE(),
    MONTO_TOTAL DECIMAL(10,2) NOT NULL,
    METODO_PAGO VARCHAR(30) NOT NULL,
    FOREIGN KEY (ID_RESERVACION) REFERENCES Reservaciones(ID_RESERVACION)
);
